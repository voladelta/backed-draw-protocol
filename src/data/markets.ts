import type { Market, Position } from "@/types/protocol"

const image = (seed: string) => `https://picsum.photos/seed/${seed}/900/1100`

const extraPositions = ({
  prefix,
  collection,
  names,
  backing,
  accent,
}: {
  prefix: string
  collection: string
  names: string[]
  backing: number
  accent: string[]
}): Position[] =>
  names.map((name, index) => ({
    id: `${prefix}-${index + 1}`,
    name,
    collection,
    image: image(`${prefix}-${index + 1}`),
    backing: Number((backing * (1 - index * 0.055)).toFixed(2)),
    probability: Number((0.07 + index * 0.013).toFixed(3)),
    earnings: Number((backing * (0.085 - index * 0.004)).toFixed(2)),
    accent: accent[index % accent.length],
  }))

